import { createHash } from 'node:crypto';
import { mkdir, readFile, readdir, unlink, writeFile } from 'node:fs/promises';
import subsetFont from 'subset-font';

const response = await fetch('https://raw.githubusercontent.com/hexschool/KCGTravel/master/datastore_search.json', { signal: AbortSignal.timeout(10000) });
if (!response.ok) throw new Error(`Dataset: HTTP ${response.status}`);
const { result: { records } } = await response.json();
const files = ['src/routes/+page.svelte', 'src/routes/+layout.svelte',
  ...['AreaCard', 'AreaSelect', 'HotButtons', 'ThemeToggle'].map(name => `src/lib/components/${name}.svelte`)];
const ui = (await Promise.all(files.map(file => readFile(file, 'utf8')))).join('\n')
  .replace(/<!--[^]*?-->|\/\*[^]*?\*\/|^\s*\/\/.*$/gm, '');
const text = spot => ['Name', 'Zone', 'Opentime', 'Add', 'Tel', 'Ticketinfo'].map(field => spot[field]).join('');
const groups = [Array.from({ length: 95 }, (_, index) => String.fromCodePoint(index + 32)).join('') + ui];
for (let start = 0; start < records.length; start += 12) {
  const value = records.slice(start, start + 12).map(text).join('');
  groups.push(value);
}
const original = await readFile('src/lib/assets/noto-sans-tc-subset.woff2');
const directory = 'src/lib/assets/fonts';
await mkdir(directory, { recursive: true });
const used = new Set();
const retained = new Set();
const rules = [];
const sizes = [];
for (const group of groups) {
  const characters = [...new Set(group)].filter(char => char.codePointAt(0) >= 32 && !used.has(char));
  if (!characters.length) continue;
  characters.forEach(char => used.add(char));
  const buffer = await subsetFont(original, characters.join(''), {
    targetFormat: 'woff2', variationAxes: { wght: { min: 400, max: 700 } },
  });
  const filename = `noto-${createHash('sha256').update(buffer).digest('hex').slice(0, 16)}.woff2`;
  await writeFile(`${directory}/${filename}`, buffer);
  retained.add(filename);
  const points = characters.map(char => char.codePointAt(0)).sort((a, b) => a - b);
  const ranges = [];
  for (let index = 0; index < points.length; index++) {
    const start = points[index];
    let end = start;
    while (points[index + 1] === end + 1) end = points[++index];
    ranges.push(`U+${start.toString(16)}${end === start ? '' : `-${end.toString(16)}`}`);
  }
  rules.push(`@font-face {\n  font-family: "Noto Sans TC Subset";\n  src: url("./fonts/${filename}") format("woff2");\n  font-style: normal;\n  font-weight: 400 700;\n  font-display: optional;\n  unicode-range: ${ranges.join(',')};\n}`);
  sizes.push(buffer.length);
}
await writeFile('src/lib/assets/fonts.css', `/* Generated by npm run assets:sync. License: /fonts/OFL.txt */\n${rules.join('\n\n')}\n`);
for (const file of await readdir(directory)) {
  if (/^noto-[a-f0-9]{16}\.woff2$/.test(file) && !retained.has(file)) await unlink(`${directory}/${file}`);
}
console.log(JSON.stringify({ fontChunks: sizes, originalBytes: original.length }));
